#!/usr/bin/env python3
"""Rasterize the approved WenKai 16 px face; no UI14 scaling or TF changes."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import argparse,hashlib,json,re
p=Path(__file__).resolve().parents[1]
a=argparse.ArgumentParser();a.add_argument('--font',type=Path,required=True);a.add_argument('--report',type=Path,required=True);a.add_argument('--output',type=Path,default=p/'src/ui16_font_data.cpp');args=a.parse_args()
assert hashlib.sha256(args.font.read_bytes()).hexdigest()=='39ad71264b588165b469e35e6afb162a378dacd1f95348160240ba9038ac3009'
face=ImageFont.truetype(str(args.font),16,layout_engine=ImageFont.Layout.BASIC)
coverage=set(range(32,127))|set(map(ord,'…←→↑↓'))
for page,first,mask in re.findall(r'\{(\d+),(\d+),\{([\d,]+)\}\}',(p/'src/ui14_font_data.cpp').read_text()):
 for n,b in enumerate(map(int,mask.split(','))):
  for bit in range(8):
   if b&(1<<bit):coverage.add(int(page)*256+n*8+bit)
pages=[];data=bytearray();advances=[];clipped=[]
for cp in sorted(coverage):
 advance=max(1,round(face.getlength(chr(cp)))) if cp<128 else 16
 mask=Image.new('L',(64,64),0);ImageDraw.Draw(mask).text((16,32),chr(cp),font=face,anchor='ls',fill=255)
 mask=mask.point(lambda v:255 if v>=128 else 0,mode='1');bb=mask.getbbox();cell=Image.new('1',(16,16),0)
 if bb:
  l,t,r,b=bb[0]-16,bb[1]-32,bb[2]-16,bb[3]-32
  if r-l>advance or b-t>16:clipped.append(cp)
  dx=max(-l,min(0,advance-r));baseline=max(-t,min(round(16*.79),16-b))
  cell.paste(mask.crop(bb),(l+dx,t+baseline))
 if not pages or pages[-1][0]!=cp>>8:pages.append([cp>>8,len(data)//32,[0]*32])
 pages[-1][2][(cp&255)//8]|=1<<(cp&7)
 data.extend(cell.tobytes())
 if cp<128:advances.append(advance)
missing=Image.new('1',(16,16));d=ImageDraw.Draw(missing);d.rectangle((2,2,13,13),outline=1);d.line((2,2,13,13),fill=1);d.line((13,2,2,13),fill=1)
with args.output.open('w') as f:
 f.write('// Generated by scripts/generate_ui16.py; WenKai 1.522 / OFL-1.1.\n#include "ui16_font.hpp"\nnamespace s3app::ui16 {\nconst Page pages[]={\n')
 for page,first,m in pages:f.write('{%d,%d,{%s}},\n'%(page,first,','.join(map(str,m))))
 f.write('};\nconst size_t pageCount=sizeof(pages)/sizeof(pages[0]);\nconst uint8_t asciiAdvance[]={'+','.join(map(str,advances))+'};\nconst uint8_t missingBits[]={'+','.join(map(str,missing.tobytes()))+'};\nconst uint8_t glyphBits[]={\n')
 for i in range(0,len(data),32):f.write(','.join(map(str,data[i:i+32]))+',\n')
 f.write('};\n}\n')
args.report.write_text(json.dumps({'font_sha256':hashlib.sha256(args.font.read_bytes()).hexdigest(),'glyphs':len(coverage),'pages':len(pages),'bitmap_bytes':len(data),'ascii_advance':advances,'oversize_ink_codepoints':clipped,'font_px':16,'threshold':128,'scope':'actual product generated asset, Unicode subset inherited UI14 plus ASCII/navigation'},indent=2))
print('UI16 glyphs',len(coverage),'bytes',len(data),'oversize ink',len(clipped))
