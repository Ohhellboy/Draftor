"""Generate C++ declarations, enum/envelope validation, explicit payload writers and docs.
The JSON is the sole machine-readable event/enum/wire registry. --check detects drift.
"""
import argparse
import json
from pathlib import Path
from schema_documentation import render_event_schema
ROOT = Path(__file__).resolve().parents[1]
SCHEMA = json.loads((ROOT/'schema/events.json').read_text())
TYPES = {'u8':'std::uint8_t','u32':'std::uint32_t','u64':'std::uint64_t'}

def outputs():
    header = ['// Generated by scripts/generate_schema.py; edit schema/events.json.', '#pragma once', '#include <cstdint>', 'namespace draftor::telemetry {']
    for name, values in SCHEMA['enums'].items():
        header += ['enum class '+name+' : std::uint8_t { '+', '.join(f'{k} = {v}' for k,v in values.items())+' };']
        header += [f'constexpr bool valid_{name}(std::uint8_t value) noexcept {{', '    switch (value) {']
        header += [f'    case {value}:' for value in values.values()]
        header += ['        return true;', '    default: return false;', '    }', '}']
    header += ['enum class EventType : std::uint16_t {']
    header += [f'    {e["cpp_name"]} = {e["id"]},' for e in SCHEMA['events']]
    header += ['};', 'constexpr bool is_known_event_type(EventType type) noexcept {', '    switch (type) {']
    header += [f'    case EventType::{e["cpp_name"]}:' for e in SCHEMA['events']]
    header += ['        return true;', '    default: return false;', '    }', '}']
    for e in SCHEMA['events']:
        header += ['struct '+e['cpp_name']+'Event {']
        header += [f'    {TYPES[f["type"]]} {f["name"]};' for f in e['fields']]
        header += ['};']
    header += ['union EventPayload {']
    header += [f'    {e["cpp_name"]}Event {e["name"].lower()};' for e in SCHEMA['events']]
    header += ['};', '} // namespace draftor::telemetry', '']
    encode = ['// Generated explicit field serialization; no struct packing.', 'switch (event.type) {']
    validate = ['// Generated enum validity rules; no separate enum registry.', 'switch (source.type) {']
    for e in SCHEMA['events']:
        encode += ['case EventType::'+e['cpp_name']+':']
        validate += ['case EventType::'+e['cpp_name']+':']
        for f in e['fields']:
            field=f'payload.{e["name"].lower()}.{f["name"]}'
            encode += [f'    writer.{f["type"]}(event.{field});']
            if 'enum' in f:
                validate += [f'    if (!valid_{f["enum"]}(source.{field})) return FilterResult::Invalid;']
                for disallowed in f.get('disallowed_enum_values',[]):
                    validate += [f'    if (source.{field} == static_cast<std::uint8_t>({f["enum"]}::{disallowed})) return FilterResult::Invalid;']
        encode += ['    break;']; validate += ['    break;']
    encode += ['default: return {EncodeStatus::InvalidEvent, 0};', '}', '']
    validate += ['default: return FilterResult::Invalid;', '}', '']
    envelope = ['// Generated required-envelope rules; zero-valued ordinary revisions remain legal.',
                '// State activity uses the caller-supplied composition_id, never business lookup.',
                'switch (source.type) {']
    for event in SCHEMA['events']:
        envelope += [f'case EventType::{event["cpp_name"]}:']
        for rule in event['required_envelope']:
            if not rule['nonzero']:
                continue # Fixed-width fields are always present; zero is a legal value.
            condition = f'source.envelope.{rule["field"]} == 0'
            if 'when' in rule:
                when = rule['when']
                owner = 'envelope' if when['source'] == 'envelope' else 'payload.'+event['name'].lower()
                field = f'source.{owner}.{when["field"]}'
                guard = f'{field} != 0' if when.get('nonzero') else f'{field} == {when["equals"]}'
                condition = f'{guard} && {condition}'
            envelope += [f'    if ({condition}) return FilterResult::Invalid;']
        envelope += ['    break;']
    envelope += ['default: return FilterResult::Invalid;', '}', '']
    constants=['// Generated wire/capacity constants; edit schema/events.json.', '#pragma once', '#include <cstddef>', '#include <cstdint>', 'namespace draftor::telemetry {']
    for name,key,type_ in [('kWireVersion','version','std::uint8_t'),('kSchemaRevision','schema_revision','std::uint8_t'),
                           ('kWireHeaderBytes','header_bytes','std::size_t'),('kMaxPayloadBytes','max_payload_bytes','std::size_t'),
                           ('kTextCapacity','text_capacity','std::size_t'),('kPathCapacity','path_capacity','std::size_t'),
                           ('kQueueCapacity','queue_capacity','std::size_t')]:
        constants += [f'constexpr {type_} {name} = {SCHEMA["wire"][key]};']
    constants += ['} // namespace draftor::telemetry','']
    return {ROOT/'include/draftor/telemetry/EventSchema.h':'\n'.join(header),
            ROOT/'include/draftor/telemetry/ProtocolConstants.h':'\n'.join(constants),
            ROOT/'src/EncodePayload.inc':'\n'.join(encode),ROOT/'src/ValidatePayload.inc':'\n'.join(validate),
            ROOT/'src/ValidateEnvelope.inc':'\n'.join(envelope),
            ROOT/'EVENT_SCHEMA.md':render_event_schema(SCHEMA)}
if __name__ == '__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text()!=content: raise SystemExit('schema drift: '+str(path))
        else: path.write_text(content)
